-- PSU Student Activity Awards authentication tables.
-- Run once in Supabase Dashboard > SQL Editor before starting server.js.

create table if not exists public.app_users (
  id bigint generated by default as identity primary key,
  username text,
  display_name text not null,
  position text not null default '',
  role text not null check (role in ('admin', 'judge')),
  password_hash text,
  password_salt text,
  access_code_lookup text,
  access_code_hash text,
  access_code_salt text,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  constraint app_users_display_name_length check (char_length(display_name) between 1 and 100),
  constraint app_users_position_length check (char_length(position) <= 100)
);

-- Migrate the earlier username/password login schema without deleting accounts.
alter table public.app_users alter column username drop not null;
alter table public.app_users alter column password_hash drop not null;
alter table public.app_users alter column password_salt drop not null;
alter table public.app_users add column if not exists access_code_lookup text;
alter table public.app_users add column if not exists access_code_hash text;
alter table public.app_users add column if not exists access_code_salt text;

create unique index if not exists app_users_username_lower_unique
  on public.app_users (lower(username));
create unique index if not exists app_users_access_code_lookup_unique
  on public.app_users (access_code_lookup) where access_code_lookup is not null;

create table if not exists public.app_sessions (
  token_hash text primary key,
  user_id bigint not null references public.app_users(id) on delete cascade,
  expires_at bigint not null,
  created_at bigint not null
);

create index if not exists app_sessions_expiry_idx on public.app_sessions (expires_at);

create table if not exists public.app_settings (
  id smallint primary key default 1 check (id = 1),
  submissions_open boolean not null default false,
  submissions_start date,
  submissions_end date,
  success_message text not null default 'ส่งผลงานสำเร็จ ระบบได้รับข้อมูลของท่านแล้ว',
  updated_at timestamptz not null default now()
);

insert into public.app_settings (id) values (1) on conflict (id) do nothing;

create table if not exists public.submissions (
  id bigint generated by default as identity primary key,
  category_type text not null check (category_type in ('person', 'project')),
  category text not null,
  title text,
  submitter_name text not null,
  student_id text not null,
  faculty text not null,
  phone text not null,
  email text,
  organization_position text,
  video_url text,
  details text,
  proposal_file_path text not null,
  proposal_file_name text not null,
  presentation_file_path text not null,
  presentation_file_name text not null,
  status text not null default 'submitted' check (status in ('submitted', 'withdrawn')),
  created_at timestamptz not null default now(),
  constraint submissions_project_title check (category_type <> 'project' or nullif(trim(title), '') is not null),
  constraint submissions_submitter_name_length check (char_length(submitter_name) between 1 and 120),
  constraint submissions_student_id_length check (char_length(student_id) between 1 and 30),
  constraint submissions_faculty_length check (char_length(faculty) between 1 and 160),
  constraint submissions_phone_length check (char_length(phone) between 1 and 40)
);

create index if not exists submissions_created_at_idx on public.submissions (created_at desc);
create index if not exists submissions_type_idx on public.submissions (category_type);

alter table public.app_users enable row level security;
alter table public.app_sessions enable row level security;
alter table public.app_settings enable row level security;
alter table public.submissions enable row level security;

-- Browser clients have no table access. The server checks each role before
-- accessing data with the server-only Supabase secret key.
revoke all on public.app_users from anon, authenticated;
revoke all on public.app_sessions from anon, authenticated;
revoke all on public.app_settings from anon, authenticated;
revoke all on public.submissions from anon, authenticated;
grant all on public.app_users to service_role;
grant all on public.app_sessions to service_role;
grant all on public.app_settings to service_role;
grant all on public.submissions to service_role;
grant usage, select on all sequences in schema public to service_role;

