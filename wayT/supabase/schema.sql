create table if not exists public.submission_scores (
  submission_id bigint not null references public.submissions(id) on delete cascade,
  judge_user_id bigint not null references public.app_users(id) on delete cascade,
  scores jsonb not null check (jsonb_typeof(scores) = 'array'),
  total smallint not null check (total between 0 and 100),
  updated_at timestamptz not null default now(),
  primary key (submission_id, judge_user_id)
);
create index if not exists submission_scores_judge_idx on public.submission_scores (judge_user_id, updated_at desc);
alter table public.submission_scores enable row level security;
revoke all on public.submission_scores from anon, authenticated;
grant all on public.submission_scores to service_role;
